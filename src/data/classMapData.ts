export interface SchoolClass {
  id: string;
  name: string; // e.g. "X TSM", "XI TITL 1"
  grade: 'X' | 'XI' | 'XII';
  major: 'TSM' | 'TKR' | 'TP' | 'TITL' | 'TKJ';
  majorFullName: string;
  waliKelas: string;
  totalStudents?: number;
}

export interface ClassSubjectAssignment {
  classId: string;
  className: string;
  subjectName: string;
  hours: number; // Jam Pelajaran (JP)
  studentCount?: number; // Khusus BK
  notes?: string;
}

export interface TeacherClassMap {
  teacherId: string;
  teacherName: string;
  nip: string;
  rank?: string;
  status: string;
  subjectCategory: 'UMUM' | 'KEJURUAN' | 'BK' | 'KEPALA_SEKOLAH';
  primarySubject: string;
  additionalDuties?: string;
  additionalHours: number;
  assignments: Record<string, ClassSubjectAssignment>; // key: classId
  totalTeachingHours: number;
  totalWorkload: number;
}

